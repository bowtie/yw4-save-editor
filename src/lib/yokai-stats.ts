function statBlock(tuple: StatTuple, offset: number): StatBlock {
  return {
    hp: tuple[offset],
    str: tuple[offset + 1],
    spr: tuple[offset + 2],
    def: tuple[offset + 3],
    res: tuple[offset + 4],
    yp: tuple[offset + 5],
  };
}

/** Resolve an alternate ParamID (boss, NPC or duplicate row) to the species'
 *  canonical playable row. Unknown IDs pass through unchanged. */
export function canonicalParamId(paramId: number): number {
  const key = paramId >>> 0;
  return ALIASES[key] ?? key;
}

/** Species stat anchors for a save ParamID, or undefined when the species has
 *  no CHARA_PARAM_INFO row. */
export function yokaiStatsFor(paramId: number): YokaiStats | undefined {
  const tuple = STATS[canonicalParamId(paramId)];
  if (!tuple) return undefined;
  return {
    level1: statBlock(tuple, 0),
    level99: statBlock(tuple, 6),
    level120: statBlock(tuple, 12),
  };
}

/** Half-up division of a non-negative integer numerator. */
function roundDiv(numerator: number, denominator: number): number {
  return Math.floor((numerator + denominator / 2) / denominator);
}

function clampLevel(level: number): number {
  return Math.max(1, Math.min(120, Math.trunc(level)));
}

/** Interpolate one stat between the level-1, level-99 and level-120 anchors.
 *  Levels outside 1..120 are clamped. */
export function statAtLevel(baseA: number, baseB: number, baseC: number, level: number): number {
  const l = clampLevel(level);
  if (l <= 99) return roundDiv(baseA * 98 + (baseB - baseA) * (l - 1), 98);
  return roundDiv(baseB * 21 + (baseC - baseB) * (l - 99), 21);
}

/** All six stats at a level, using the species' three anchors. */
export function statsAtLevel(anchors: YokaiStats, level: number): StatBlock {
  const at = (key: StatKey) =>
    statAtLevel(anchors.level1[key], anchors.level99[key], anchors.level120[key], level);
  return {
    hp: at("hp"),
    str: at("str"),
    spr: at("spr"),
    def: at("def"),
    res: at("res"),
    yp: at("yp"),
  };
}

/** Base stats for a save ParamID at a level, or undefined when unknown. */
export function yokaiStatsAtLevel(paramId: number, level: number): StatBlock | undefined {
  const anchors = yokaiStatsFor(paramId);
  return anchors ? statsAtLevel(anchors, level) : undefined;
}

const STAT_SCALE_CACHE = new Map<number, StatBlock>();

/** Strongest value of each stat among player-scale species at a level.  A full
 *  bar in the Yo-kai panel is the best yo-kai, ally summon or protagonist at
 *  that level.  Cached per level. */
export function playerStatScaleAtLevel(level: number): StatBlock {
  const l = clampLevel(level);
  const cached = STAT_SCALE_CACHE.get(l);
  if (cached) return cached;
  const scale: StatBlock = { hp: 1, str: 1, spr: 1, def: 1, res: 1, yp: 1 };
  for (const paramId of PLAYER_SCALE_PARAM_IDS) {
    const stats = yokaiStatsAtLevel(paramId, l);
    if (!stats) continue;
    for (const key of STAT_KEYS) scale[key] = Math.max(scale[key], stats[key]);
  }
  STAT_SCALE_CACHE.set(l, scale);
  return scale;
}
