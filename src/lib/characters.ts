const baseNames = new Map<number, string>();
const paramNames = new Map<number, string>();
for (const c of CHARA_NAMES) {
  if (c.baseId !== null && !baseNames.has(c.baseId)) baseNames.set(c.baseId, c.name);
  if (c.paramId !== null && !paramNames.has(c.paramId))
    paramNames.set(c.paramId, c.form ? `${c.name} (${c.form})` : c.name);
}

/** Name for a yo-kai soul table entry (keyed by BaseID). */
export function nameForBase(id: number): string | null {
  return baseNames.get(id >>> 0) ?? null;
}

/** Name for a party/yo-kai slot species (keyed by ParamID). */
export function nameForParam(id: number): string | null {
  return paramNames.get(id >>> 0) ?? null;
}
