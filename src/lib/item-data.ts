export interface ItemInfo {
  name: string;
  category: ItemCategory;
  /** In-game star rating, 1-5 (souls are always 1; the game shows none). */
  rarity: number;
}

const byCrc = new Map<number, ItemInfo>();
for (const [crc, name, category, rarity] of ITEMS) byCrc.set(crc >>> 0, { name, category, rarity });

export function itemByCrc(crc: number): ItemInfo | undefined {
  return byCrc.get(crc >>> 0);
}

export function itemsOfCategory(category: ItemCategory): (ItemInfo & { crc: number })[] {
  return ITEMS.filter(([, , c]) => c === category).map(([crc, name, , rarity]) => ({
    crc,
    name,
    category,
    rarity,
  }));
}
